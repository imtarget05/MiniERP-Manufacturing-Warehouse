-- ============================================================================
-- PROJECT: FactoryFlow
-- FILE: sql/12_integration_outbox_schema.sql
-- TARGET: Oracle Database 19c / 21c / 23c
-- DESCRIPTION: Additive, rerunnable foundation for external integration events.
--
-- This migration intentionally creates no trigger and changes no ERP workflow.
-- ERP_OPERATIONS / ERP_AUTOMATION / ERP_TRACEABILITY currently commit internally;
-- producers may be added only after Oracle QA proves an event insert and the
-- corresponding business write share one caller-owned transaction.
-- ============================================================================

DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM user_tables WHERE table_name = 'INTEGRATION_OUTBOX';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE INTEGRATION_OUTBOX (
        EVENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        EVENT_TYPE VARCHAR2(100) NOT NULL,
        AGGREGATE_TYPE VARCHAR2(60) NOT NULL,
        AGGREGATE_ID VARCHAR2(100) NOT NULL,
        PAYLOAD_JSON CLOB NOT NULL CONSTRAINT CK_IOB_PAYLOAD_JSON CHECK (PAYLOAD_JSON IS JSON),
        IDEMPOTENCY_KEY VARCHAR2(160) NOT NULL,
        CORRELATION_ID VARCHAR2(60),
        STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL
          CONSTRAINT CK_IOB_STATUS CHECK (STATUS IN
            ('PENDING','IN_PROGRESS','PUBLISHED','FAILED','DEAD_LETTER')),
        ATTEMPT_COUNT NUMBER DEFAULT 0 NOT NULL CONSTRAINT CK_IOB_ATTEMPTS CHECK (ATTEMPT_COUNT >= 0),
        AVAILABLE_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        LOCKED_UNTIL TIMESTAMP(6) WITH TIME ZONE,
        LAST_ERROR VARCHAR2(1000),
        PUBLISHED_AT TIMESTAMP(6) WITH TIME ZONE,
        CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT UQ_IOB_IDEMPOTENCY UNIQUE (IDEMPOTENCY_KEY)
      )]';
  END IF;
END;
/

DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM user_indexes WHERE index_name = 'IX_IOB_DISPATCH';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX IX_IOB_DISPATCH ON INTEGRATION_OUTBOX (STATUS, AVAILABLE_AT, EVENT_ID)';
  END IF;
END;
/
