-- Clean up existing tables safely if re-running
BEGIN
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
    'CHANGE_REQUEST', 'ERROR_LOG', 'USER_ROLE', 'ERP_ROLE', 'APP_USER',
    'INVENTORY_TRANSACTION', 'PURCHASE_ORDER', 'PRODUCTION_ORDER',
    'BOM_DETAIL', 'BOM', 'STOCK', 'ITEM', 'WAREHOUSE'
  ))
  LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
  END LOOP;
END;
/

-- 1. WAREHOUSE: Kho lưu trữ vật tư và thành phẩm
CREATE TABLE WAREHOUSE (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODE        VARCHAR2(20)  NOT NULL UNIQUE,
  NAME        VARCHAR2(100) NOT NULL,
  LOCATION    VARCHAR2(200),
  IS_ACTIVE   NUMBER(1)     DEFAULT 1 NOT NULL CONSTRAINT CK_WH_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
  CREATED_AT  DATE          DEFAULT SYSDATE NOT NULL
);

-- 2. ITEM: Danh mục vật tư (RAW) và Thành phẩm (FG)
CREATE TABLE ITEM (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODE        VARCHAR2(30)  NOT NULL UNIQUE,
  NAME        VARCHAR2(150) NOT NULL,
  ITEM_TYPE   VARCHAR2(10)  NOT NULL CONSTRAINT CK_ITEM_TYPE CHECK (ITEM_TYPE IN ('RAW', 'FG')),
  UOM         VARCHAR2(10)  DEFAULT 'PCS' NOT NULL,
  MIN_STOCK   NUMBER        DEFAULT 0     NOT NULL CONSTRAINT CK_ITEM_MIN CHECK (MIN_STOCK >= 0),
  CREATED_AT  DATE          DEFAULT SYSDATE NOT NULL
);

-- 3. STOCK: Tồn kho thực tế theo từng Kho và từng Vật tư
CREATE TABLE STOCK (
  WAREHOUSE_ID NUMBER NOT NULL CONSTRAINT FK_STOCK_WH   REFERENCES WAREHOUSE(ID),
  ITEM_ID      NUMBER NOT NULL CONSTRAINT FK_STOCK_ITEM REFERENCES ITEM(ID),
  QTY          NUMBER DEFAULT 0 NOT NULL CONSTRAINT CK_STOCK_QTY CHECK (QTY >= 0),
  UPDATED_AT   DATE   DEFAULT SYSDATE NOT NULL,
  CONSTRAINT UQ_STOCK PRIMARY KEY (WAREHOUSE_ID, ITEM_ID)
);

-- 4. BOM (Bill of Materials): Định mức sản xuất cho từng Thành phẩm
CREATE TABLE BOM (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  FG_ITEM_ID  NUMBER       NOT NULL CONSTRAINT FK_BOM_FG REFERENCES ITEM(ID),
  VERSION     VARCHAR2(20) NOT NULL,
  DESCRIPTION VARCHAR2(255),
  STATUS      VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL CONSTRAINT CK_BOM_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
  CREATED_AT  DATE         DEFAULT SYSDATE NOT NULL,
  CONSTRAINT UQ_BOM UNIQUE (FG_ITEM_ID, VERSION)
);

-- 5. BOM_DETAIL: Chi tiết nguyên phụ liệu tiêu hao cho 1 đơn vị Thành phẩm
CREATE TABLE BOM_DETAIL (
  BOM_ID       NUMBER NOT NULL CONSTRAINT FK_BD_BOM  REFERENCES BOM(ID) ON DELETE CASCADE,
  MAT_ITEM_ID  NUMBER NOT NULL CONSTRAINT FK_BD_ITEM REFERENCES ITEM(ID),
  QTY_REQUIRED NUMBER NOT NULL CONSTRAINT CK_BD_QTY  CHECK (QTY_REQUIRED > 0),
  CONSTRAINT PK_BOMDET PRIMARY KEY (BOM_ID, MAT_ITEM_ID)
);

-- 6. PRODUCTION_ORDER: Lệnh sản xuất thành phẩm tại xưởng
CREATE TABLE PRODUCTION_ORDER (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PO_NO        VARCHAR2(30) NOT NULL UNIQUE,
  FG_ITEM_ID   NUMBER       NOT NULL CONSTRAINT FK_PO_FG REFERENCES ITEM(ID),
  QTY_PLANNED  NUMBER       NOT NULL CONSTRAINT CK_PO_QTY CHECK (QTY_PLANNED > 0),
  QTY_DONE     NUMBER       DEFAULT 0 NOT NULL,
  STATUS       VARCHAR2(15) DEFAULT 'CREATED' NOT NULL 
               CONSTRAINT CK_PO_STATUS CHECK (STATUS IN ('CREATED', 'RELEASED', 'COMPLETED', 'CANCELLED')),
  WAREHOUSE_ID NUMBER       NOT NULL CONSTRAINT FK_PO_WH REFERENCES WAREHOUSE(ID),
  CREATED_AT   DATE         DEFAULT SYSDATE NOT NULL,
  COMPLETED_AT DATE
);

-- 7. PURCHASE_ORDER: Đơn mua nguyên phụ liệu từ nhà cung ứng
CREATE TABLE PURCHASE_ORDER (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PO_NO        VARCHAR2(30) NOT NULL UNIQUE,
  ITEM_ID      NUMBER       NOT NULL CONSTRAINT FK_PR_ITEM REFERENCES ITEM(ID),
  QTY          NUMBER       NOT NULL CONSTRAINT CK_PR_QTY CHECK (QTY > 0),
  WAREHOUSE_ID NUMBER       NOT NULL CONSTRAINT FK_PR_WH REFERENCES WAREHOUSE(ID),
  STATUS       VARCHAR2(15) DEFAULT 'CREATED' NOT NULL 
               CONSTRAINT CK_PR_STATUS CHECK (STATUS IN ('CREATED', 'RECEIVED', 'CANCELLED')),
  CREATED_AT   DATE         DEFAULT SYSDATE NOT NULL,
  RECEIVED_AT  DATE
);

-- 8. INVENTORY_TRANSACTION: Nhật ký biến động kho (Audit trail bất biến)
CREATE TABLE INVENTORY_TRANSACTION (
  ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TXN_TYPE      VARCHAR2(15) NOT NULL CONSTRAINT CK_TXN_TYPE 
                CHECK (TXN_TYPE IN ('STOCK_IN', 'STOCK_OUT', 'MFG_CONSUME', 'MFG_OUTPUT', 'ADJUSTMENT')),
  ITEM_ID       NUMBER NOT NULL CONSTRAINT FK_TXN_ITEM REFERENCES ITEM(ID),
  WAREHOUSE_ID  NUMBER NOT NULL CONSTRAINT FK_TXN_WH   REFERENCES WAREHOUSE(ID),
  QTY           NUMBER NOT NULL,
  BALANCE_AFTER NUMBER NOT NULL,
  REF_NO        VARCHAR2(50),
  CREATED_BY    VARCHAR2(50) DEFAULT 'system' NOT NULL,
  CREATED_AT    DATE         DEFAULT SYSDATE NOT NULL
);

-- 9. APP_USER: Người dùng hệ thống ERP
CREATE TABLE APP_USER (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USERNAME    VARCHAR2(50)  NOT NULL UNIQUE,
  FULLNAME    VARCHAR2(120),
  DEPT        VARCHAR2(50),
  PASSWORD    VARCHAR2(100) NOT NULL,
  IS_ACTIVE   NUMBER(1)     DEFAULT 1 NOT NULL,
  CREATED_AT  DATE          DEFAULT SYSDATE NOT NULL
);

-- 10. ERP_ROLE & USER_ROLE: Phân quyền vai trò
CREATE TABLE ERP_ROLE (
  ID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME VARCHAR2(40) NOT NULL UNIQUE
);

CREATE TABLE USER_ROLE (
  USER_ID NUMBER NOT NULL CONSTRAINT FK_UR_USER REFERENCES APP_USER(ID) ON DELETE CASCADE,
  ROLE_ID NUMBER NOT NULL CONSTRAINT FK_UR_ROLE REFERENCES ERP_ROLE(ID) ON DELETE CASCADE,
  CONSTRAINT PK_USERROLE PRIMARY KEY (USER_ID, ROLE_ID)
);

-- 11. ERROR_LOG: Bảng ghi nhận sự cố nghiệp vụ (hỗ trợ ERP troubleshooting)
CREATE TABLE ERROR_LOG (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ERR_CODE   VARCHAR2(30)   NOT NULL,
  MESSAGE    VARCHAR2(1000) NOT NULL,
  PROC_NAME  VARCHAR2(60),
  REF_NO     VARCHAR2(50),
  CREATED_BY VARCHAR2(50) DEFAULT 'system' NOT NULL,
  CREATED_AT DATE DEFAULT SYSDATE NOT NULL
);

-- 12. CHANGE_REQUEST: Phiếu yêu cầu thay đổi / điều chỉnh dữ liệu sản xuất
CREATE TABLE CHANGE_REQUEST (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CR_NO      VARCHAR2(30) NOT NULL UNIQUE,
  TITLE      VARCHAR2(200) NOT NULL,
  REQ_TYPE   VARCHAR2(30) NOT NULL 
             CONSTRAINT CK_CR_TYPE CHECK (REQ_TYPE IN ('INCIDENT', 'DATA_FIX', 'CONFIG', 'ENHANCEMENT')),
  REF_NO     VARCHAR2(50),
  ROOT_CAUSE VARCHAR2(1000),
  FIX_ACTION VARCHAR2(1000),
  STATUS     VARCHAR2(20) DEFAULT 'OPEN' NOT NULL 
             CONSTRAINT CK_CR_STATUS CHECK (STATUS IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),
  REQUESTER  VARCHAR2(50),
  CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
  CLOSED_AT  DATE
);

-- Create helpful operational indexes
CREATE INDEX IX_STOCK_ITEM ON STOCK(ITEM_ID);
CREATE INDEX IX_TXN_REF ON INVENTORY_TRANSACTION(REF_NO);
CREATE INDEX IX_TXN_DATE ON INVENTORY_TRANSACTION(CREATED_AT);
CREATE INDEX IX_PO_STATUS ON PRODUCTION_ORDER(STATUS);
CREATE INDEX IX_ERR_REF ON ERROR_LOG(REF_NO);
