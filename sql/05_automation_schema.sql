-- 5.1 Widen the PRODUCTION_ORDER lifecycle used by the automation layer.
--     Legacy states stay valid (ERP_OPERATIONS still writes RELEASED on
--     create and COMPLETED/CANCELLED on close). New states:
--       MATERIAL_CHECK   material availability check in evaluation
--       WAITING_MATERIAL check finished: >= 1 material is short
--       READY            all materials verified / soft-reserved
--       IN_PROGRESS      completion wrapper running (transient)
--     STATUS is widened to VARCHAR2(20): 'WAITING_MATERIAL' is 16 chars.
DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt
    FROM user_constraints
   WHERE table_name = 'PRODUCTION_ORDER'
     AND constraint_name = 'CK_PO_STATUS';
  IF v_cnt > 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PRODUCTION_ORDER DROP CONSTRAINT CK_PO_STATUS';
  END IF;
END;
/

ALTER TABLE PRODUCTION_ORDER ADD CONSTRAINT CK_PO_STATUS CHECK (STATUS IN (
  'CREATED', 'RELEASED', 'MATERIAL_CHECK', 'WAITING_MATERIAL', 'READY',
  'IN_PROGRESS', 'COMPLETED', 'CANCELLED'
));

-- 5.1.1 Widen STATUS to accommodate new automation states (WAITING_MATERIAL=16 chars).
--     The check constraint above defines the legal values; this statement raises the
--     column width so INSERT/UPDATE never fail with ORA-12899.
DECLARE
  v_len NUMBER;
BEGIN
  SELECT data_length INTO v_len
    FROM user_tab_columns
   WHERE table_name = 'PRODUCTION_ORDER' AND column_name = 'STATUS';
  IF v_len < 20 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PRODUCTION_ORDER MODIFY STATUS VARCHAR2(20)';
  END IF;
END;
/

-- 5.2 Extend ITEM with replenishment parameters (inputs of the W3 rule:
--     suggested = AVG_DAILY_USAGE * LEAD_TIME_DAYS + SAFETY_STOCK - available).
--     NOT NULL DEFAULT 0 keeps every existing INSERT working unchanged;
--     sql/03_seed.sql backfills the demo catalogue (it runs after this file).
DECLARE
  PROCEDURE add_col(p_col VARCHAR2, p_def VARCHAR2) IS
    v_cnt NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_cnt
      FROM user_tab_columns
     WHERE table_name = 'ITEM' AND column_name = p_col;
    IF v_cnt = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE ITEM ADD (' || p_col || ' ' || p_def || ')';
    END IF;
  END add_col;
BEGIN
  add_col('REORDER_POINT',   'NUMBER DEFAULT 0 NOT NULL');
  add_col('SAFETY_STOCK',    'NUMBER DEFAULT 0 NOT NULL');
  add_col('AVG_DAILY_USAGE', 'NUMBER DEFAULT 0 NOT NULL');
  add_col('LEAD_TIME_DAYS',  'NUMBER DEFAULT 0 NOT NULL');
END;
/

-- 5.3 STOCK_RESERVATION: soft hold of material for a production order.
--     Physical STOCK rows are untouched; availability is computed as
--     STOCK.QTY - SUM(ACTIVE holds of *other* orders).
--     ON DELETE CASCADE keeps cleanup automatic with the PO001 scenario.
DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM user_tables WHERE table_name = 'STOCK_RESERVATION';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE STOCK_RESERVATION (
        ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        PO_NO        VARCHAR2(30) NOT NULL
                     CONSTRAINT FK_RES_PO REFERENCES PRODUCTION_ORDER(PO_NO) ON DELETE CASCADE,
        ITEM_ID      NUMBER NOT NULL CONSTRAINT FK_RES_ITEM REFERENCES ITEM(ID),
        WAREHOUSE_ID NUMBER NOT NULL CONSTRAINT FK_RES_WH   REFERENCES WAREHOUSE(ID),
        QTY          NUMBER NOT NULL CONSTRAINT CK_RES_QTY  CHECK (QTY > 0),
        STATUS       VARCHAR2(15) DEFAULT 'ACTIVE' NOT NULL
                     CONSTRAINT CK_RES_STATUS CHECK (STATUS IN ('ACTIVE', 'RELEASED', 'CONSUMED')),
        CREATED_AT   DATE DEFAULT SYSDATE NOT NULL,
        UPDATED_AT   DATE DEFAULT SYSDATE NOT NULL
      )]';
  END IF;
END;
/

