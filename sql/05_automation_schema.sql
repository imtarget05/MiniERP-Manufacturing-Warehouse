CREATE OR REPLACE TRIGGER TRG_PO_STATE_HISTORY
AFTER UPDATE OF STATUS ON PRODUCTION_ORDER
FOR EACH ROW
WHEN (NEW.STATUS <> OLD.STATUS)
BEGIN
  INSERT INTO PO_STATE_HISTORY (PO_NO, FROM_STATE, TO_STATE, REASON, CHANGED_BY)
  VALUES (:OLD.PO_NO, :OLD.STATUS, :NEW.STATUS, 'status-transition', 'system');
END;
