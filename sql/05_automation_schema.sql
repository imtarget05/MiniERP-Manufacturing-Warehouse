-- 5.1 Widen the PRODUCTION_ORDER lifecycle used by the automation layer.
--     Legacy states stay valid (ERP_OPERATIONS still writes RELEASED on
--     create and COMPLETED/CANCELLED on close). New states:
--       MATERIAL_CHECK   material availability check in evaluation
--       WAITING_MATERIAL check finished: >= 1 material is short
--       READY            all materials verified / soft-reserved
--       IN_PROGRESS      completion wrapper running (transient)
--     STATUS is widened to VARCHAR2(20): 'WAITING_MATERIAL' is 16 chars.
DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt
    FROM user_constraints
   WHERE table_name = 'PRODUCTION_ORDER'
     AND constraint_name = 'CK_PO_STATUS';
  IF v_cnt > 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PRODUCTION_ORDER DROP CONSTRAINT CK_PO_STATUS';
  END IF;
END;
/

ALTER TABLE PRODUCTION_ORDER ADD CONSTRAINT CK_PO_STATUS CHECK (STATUS IN (
  'CREATED', 'RELEASED', 'MATERIAL_CHECK', 'WAITING_MATERIAL', 'READY',
  'IN_PROGRESS', 'COMPLETED', 'CANCELLED'
));

-- 5.1.1 Widen STATUS to accommodate new automation states (WAITING_MATERIAL=16 chars).
--     The check constraint above defines the legal values; this statement raises the
--     column width so INSERT/UPDATE never fail with ORA-12899.
DECLARE
  v_len NUMBER;
BEGIN
  SELECT data_length INTO v_len
    FROM user_tab_columns
   WHERE table_name = 'PRODUCTION_ORDER' AND column_name = 'STATUS';
  IF v_len < 20 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PRODUCTION_ORDER MODIFY STATUS VARCHAR2(20)';
  END IF;
END;
