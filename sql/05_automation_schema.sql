    EXECUTE IMMEDIATE q'[
      CREATE TABLE APPROVAL_REQUEST (
        ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        APPROVAL_NO  VARCHAR2(30) NOT NULL UNIQUE,
        ACTION       VARCHAR2(40) NOT NULL
                     CONSTRAINT CK_APV_ACTION CHECK (ACTION IN
