    EXECUTE IMMEDIATE 'ALTER TABLE PO_STATE_HISTORY MODIFY FROM_STATE VARCHAR2(20)';
  END IF;
  IF v_len_to < 20 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PO_STATE_HISTORY MODIFY TO_STATE VARCHAR2(20)';
  END IF;
END;
/

DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM user_indexes WHERE index_name = 'IX_HIST_PO';
