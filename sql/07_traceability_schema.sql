-- 7.1 ITEM traceability configuration (additive columns, safe defaults).
DECLARE
  PROCEDURE add_col(p_col VARCHAR2, p_def VARCHAR2) IS
    v_cnt NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_cnt FROM user_tab_columns
     WHERE table_name = 'ITEM' AND column_name = p_col;
    IF v_cnt = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE ITEM ADD (' || p_col || ' ' || p_def || ')';
    END IF;
  END add_col;
BEGIN
  add_col('TRACE_MODE',      'VARCHAR2(10) DEFAULT ''NONE'' NOT NULL');
  add_col('SHELF_LIFE_DAYS', 'NUMBER');
  add_col('LABEL_TEMPLATE',  'VARCHAR2(50) DEFAULT ''DEFAULT''');
END;
/

DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM user_constraints
   WHERE table_name = 'ITEM' AND constraint_name = 'CK_ITEM_TRACE_MODE';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ITEM ADD CONSTRAINT CK_ITEM_TRACE_MODE ' ||
      'CHECK (TRACE_MODE IN (''NONE'',''LOT''))';
  END IF;
END;
/

-- 7.2 WAREHOUSE_LOCATION: rack/bin/staging/line positions in a warehouse.
